PROGRESSIONS = {
    "C_major": ((60, 64, 67), (55, 59, 62), (57, 60, 64), (53, 57, 60)),
    "A_minor": ((57, 60, 64), (53, 57, 60), (60, 64, 67), (55, 59, 62)),
}


def sample_dir() -> Path:
    return Path(os.environ.get("KES_SAMPLE_DIR", str(Path.home() / "kes-env/samples")))


@lru_cache(maxsize=24)
def _read_sample(path: Path) -> np.ndarray:
    decoded = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", str(path), "-ac", "1", "-ar", str(SR),
         "-f", "f32le", "-acodec", "pcm_f32le", "-"],
        check=True, capture_output=True,
    ).stdout
    audio = np.frombuffer(decoded, dtype="<f4").copy()
    if len(audio) < SR // 10:
        raise ValueError(f"采样过短：{path}")
    return audio


def _note(sample: np.ndarray, source_midi: int, target_midi: int, seconds: float) -> np.ndarray:
    """线性重采样移调；有终点淡出，避免截断点击声。"""
    n = max(1, int(seconds * SR))
    rate = 2 ** ((target_midi - source_midi) / 12)
    positions = np.arange(n, dtype=np.float64) * rate
    result = np.interp(positions, np.arange(len(sample)), sample, right=0).astype(np.float32)
    fade = min(n, int(0.08 * SR))
    result[-fade:] *= np.linspace(1, 0, fade, dtype=np.float32)
    return result


def _add(out: np.ndarray, start: int, note: np.ndarray, gain: float) -> None:
    if start >= len(out):
        return
    end = min(len(out), start + len(note))
    out[start:end] += note[:end - start] * gain


def render(total_s: float, style_id: str = "clay", samples: Path | None = None) -> tuple[np.ndarray, dict]:
    """按风格包编曲。对应乐器采样齐备则用真实采样，否则独立回退到程序合成。"""
    config = load_style(style_id).get("music_config", {"mode": "C_major", "bpm": 96, "instrument": "vsco2_ce_harp"})
    bpm = config["bpm"]
    inst_id = config.get("instrument", "vsco2_ce_harp")
    asset_source, note_map = INSTRUMENTS.get(inst_id, INSTRUMENTS["vsco2_ce_harp"])
    base_dir = samples or sample_dir()
    paths = {midi: base_dir / name for midi, name in note_map.items()}
    try:
        if not all(path.is_file() for path in paths.values()):
            raise FileNotFoundError(f"{inst_id} 采样不全")
        recordings = {midi: _read_sample(path) for midi, path in paths.items()}
    except (FileNotFoundError, ValueError, OSError, subprocess.CalledProcessError):
        return synth.bgm(total_s, bpm=bpm), {
            "kind": "procedural_fallback", "asset_source": "kes:synth",
            "license": "original (generated by KES code)", "style": style_id,
        }

    total = int(total_s * SR)
    out = np.zeros(total, dtype=np.float32)
    beat = 60 / bpm
    bar_s = 4 * beat
    chords = PROGRESSIONS[config["mode"]]

    def note_at(pitch: int, duration: float) -> np.ndarray:
        source = min(recordings, key=lambda n: abs(n - pitch))
        return _note(recordings[source], source, pitch, duration)

    for bar in range(int(np.ceil(total_s / bar_s))):
        chord = chords[bar % len(chords)]
        origin = bar * bar_s
        _add(out, int(origin * SR), note_at(chord[0] - 12, bar_s), 0.23)
        for step, index in enumerate((0, 1, 2, 1, 0, 2, 1, 2)):
            at = int((origin + step * beat / 2) * SR)
            _add(out, at, note_at(chord[index] + 12, beat * 0.9), 0.14)
        for offset, pitch in ((2, chord[2] + 12), (3, chord[1] + 12)):
            _add(out, int((origin + offset * beat) * SR), note_at(pitch, beat * 0.7), 0.11)
    return out, {"kind": "sampled_original_composition", "asset_source": asset_source,
                 "license": "CC0-1.0 (recordings); KES original arrangement", "style": style_id,
                 "mode": config["mode"], "bpm": bpm, "instrument": inst_id}
